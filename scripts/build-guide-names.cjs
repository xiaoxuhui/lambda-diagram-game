const fs=require('node:fs'),path=require('node:path');

// Read raw teaching definitions, never the already renamed display documents.
// Deduplicating sources here keeps the browser catalog independent of its UI.
function buildGuideNames(guideModule='guide'){
  const base=path.resolve(__dirname,'..'),P=require('../src/presets.js'),G=require(path.join(base,'src',guideModule+'.js'));
  const symbols=[],indices=new Map();
  const lessons=P.examples.map(example=>{
    const doc=G.rawLesson(example),ids=doc.symbols.map(({name,source})=>{
      const key=name+'\0'+source;
      if(!indices.has(key)){indices.set(key,symbols.length);symbols.push({name,source});}
      return indices.get(key);
    });
    return {key:example.name,symbols:ids,snippets:[doc.core,doc.foundation,doc.walkthrough,...doc.steps.map(step=>step[2]??'')]};
  });
  const source="// Generated by scripts/build-guide-names.cjs from all raw tutorial definitions.\n(function(root){'use strict';const data="+JSON.stringify({symbols,lessons})+";root.LambdaGuideNameData=data;if(typeof module!=='undefined'&&module.exports)module.exports=data;})(typeof globalThis!=='undefined'?globalThis:window);\n";
  fs.writeFileSync(path.join(base,'src/guide-name-data.js'),source);
  return {lessons:lessons.length,symbols:symbols.length};
}
module.exports=buildGuideNames;
if(require.main===module)console.log(buildGuideNames(process.argv[2]||'guide'));
